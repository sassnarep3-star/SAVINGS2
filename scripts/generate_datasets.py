def calc_account_return(acct: dict, principal: float, years: float) -> dict:
    """Exact compound interest + verified promotional bonus where eligible."""
    apy = acct["apy_percent"]
    if apy is None:
        return {
            "verified": False,
            "base_interest_usd": None,
            "promo_bonus_usd": None,
            "total_return_usd": None,
            "ending_balance_usd": None,
            "effective_annualized_pct": None,
            "single_owner_fdic_insured_usd": min(principal, acct["fdic_sweep_max_usd"] or acct["fdic_insured_max_single_usd"]),
            "single_owner_uninsured_principal_usd": max(0.0, principal - (acct["fdic_sweep_max_usd"] or acct["fdic_insured_max_single_usd"])),
        }

    # Special tier logic where primary disclosures restrict APY by minimum deposit
    effective_base_apy = apy
    if acct["id"] == "cit-platinum-savings" and principal < 5000:
        effective_base_apy = 0.25
    elif acct["id"] == "barclays-tiered-savings" and principal < 250000:
        effective_base_apy = 3.50
    elif acct["id"] in ("usbank-smartly-relationship", "wellsfargo-platinum-new") and principal < 25000:
        if acct["id"] == "usbank-smartly-relationship":
            effective_base_apy = 2.00 if principal >= 5000 else 1.00
        else:
            effective_base_apy = 0.01

    base_ending = principal * ((1.0 + effective_base_apy / 100.0) ** years)
    base_interest = round(base_ending - principal, 2)

    # Calculate verified promotional extra yield / cash bonus when lock horizon is satisfied
    promo_extra = 0.0
    if acct["id"] == "capitalone-360-performance" and years >= 0.30:  # >= 105 days hold
        if principal >= 100000:
            promo_extra = 1500.0
        elif principal >= 50000:
            promo_extra = 750.0
        elif principal >= 20000:
            promo_extra = 300.0
    elif acct["id"] == "cit-platinum-savings":
        boost_years = min(years, 0.50)
        rem_years = max(0.0, years - 0.50)
        boost_rate = 0.0425 if principal >= 5000 else 0.0075
        rem_rate = effective_base_apy / 100.0
        boosted_ending = principal * (((1.0 + boost_rate) ** boost_years) * ((1.0 + rem_rate) ** rem_years))
        promo_extra = round(boosted_ending - base_ending, 2)
    elif acct["id"] == "barclays-tiered-savings" and principal >= 25000 and years >= 0.42:  # >= 150 days (30d fund + 120d hold)
        promo_extra = 200.0
    elif acct["id"] == "sofi-checking-savings-dd":
        # +1.10% APY boost for up to first 0.50 years (4.40% vs 3.30%) + $400 cash bonus (assuming >=$5k DD)
        boost_years = min(years, 0.50)
        rem_years = max(0.0, years - 0.50)
        boosted_ending = principal * ((1.044 ** boost_years) * (1.033 ** rem_years))
        cash_bonus = 400.0 if years >= 0.25 else 0.0
        promo_extra = round((boosted_ending - base_ending) + cash_bonus, 2)
    elif acct["id"] == "marcus-online-savings":
        # With 1 referral: +1.00% boost for 0.25 yrs
        boost_years = min(years, 0.25)
        rem_years = max(0.0, years - 0.25)
        boosted_ending = principal * ((1.045 ** boost_years) * (1.035 ** rem_years))
        promo_extra = round(boosted_ending - base_ending, 2)
    elif acct["id"] == "chase-savings" and principal >= 15000 and years >= 0.25:
        promo_extra = 200.0
    elif acct["id"] == "bmo-savings-builder" and years >= 1.0:
        promo_extra = 60.0

    total_return = round(base_interest + promo_extra, 2)
    ending_balance = round(principal + total_return, 2)
    eff_cagr = round((((ending_balance / principal) ** (1.0 / years)) - 1.0) * 100.0, 2)
    cap = acct["fdic_sweep_max_usd"] or acct["fdic_insured_max_single_usd"]
    insured_end = round(min(ending_balance, cap), 2)
    uninsured_end = round(max(0.0, ending_balance - cap), 2)

    return {
        "verified": True,
        "applied_base_apy_percent": effective_base_apy,
        "base_interest_usd": base_interest,
        "promo_bonus_usd": round(promo_extra, 2),
        "total_return_usd": total_return,
        "ending_balance_usd": ending_balance,
        "effective_annualized_pct": eff_cagr,
        "fdic_single_cap_usd": cap,
        "ending_fdic_insured_usd": insured_end,
        "ending_uninsured_overflow_usd": uninsured_end,
    }


