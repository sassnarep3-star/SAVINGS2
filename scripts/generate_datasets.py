def main() -> None:
    # Build complete returns matrix across all 18 accounts x 10 deposit sizes x 6 horizons
    matrix_rows = []
    for acct in ACCOUNTS:
        by_deposit = {}
        for dep in DEPOSIT_TIERS:
            by_horizon = {}
            for h in HORIZONS:
                by_horizon[h["key"]] = calc_account_return(acct, float(dep), h["years"])
            by_deposit[str(dep)] = by_horizon
        matrix_rows.append(
            {
                "account_id": acct["id"],
                "brand_name": acct["brand_name"],
                "account_name": acct["account_name"],
                "fdic_cert": acct["fdic_cert"],
                "apy_status": acct["apy_status"],
                "apy_percent": acct["apy_percent"],
                "official_rate_as_of_date": acct["official_rate_as_of_date"],
                "verified_date": acct["verified_date"],
                "rate_source_url": acct["rate_source_url"],
                "projections": by_deposit,
            }
        )

    (DATASETS_DIR / "national-banks.json").write_text(
        json.dumps(
            {
                "metadata": {
                    "account_open_date": OPEN_DATE,
                    "verification_date_utc": VERIFIED_DATE,
                    "total_accounts": len(ACCOUNTS),
                    "verified_apy_accounts": sum(1 for a in ACCOUNTS if a["apy_percent"] is not None),
                    "flagged_blank_apy_accounts": sum(1 for a in ACCOUNTS if a["apy_percent"] is None),
                },
                "accounts": ACCOUNTS,
            },
            indent=2,
        )
        + "\n"
    )

    (DATASETS_DIR / "promotions.json").write_text(
        json.dumps(
            {
                "metadata": {
                    "verification_date_utc": VERIFIED_DATE,
                    "account_open_date": OPEN_DATE,
                    "total_promotions": len(PROMOTIONS),
                },
                "promotions": PROMOTIONS,
            },
            indent=2,
        )
        + "\n"
    )

    (DATASETS_DIR / "returns-matrix.json").write_text(
        json.dumps(
            {
                "metadata": {
                    "account_open_date": OPEN_DATE,
                    "verification_date_utc": VERIFIED_DATE,
                    "deposit_tiers_usd": DEPOSIT_TIERS,
                    "horizons": HORIZONS,
                    "formula_note": "Ending Balance = Principal * (1 + APY)^Years + Confirmed Promo Bonus (where minimum deposit & hold window are met). Savings APYs are variable and subject to change after account opening.",
                },
                "accounts": matrix_rows,
                "optimal_fdic_portfolios": PORTFOLIO_STRATEGIES,
            },
            indent=2,
        )
        + "\n"
    )

    (DATASETS_DIR / "flagged-items.json").write_text(
        json.dumps(
            {
                "metadata": {
                    "verification_date_utc": VERIFIED_DATE,
                    "total_flagged_items": len(FLAGGED_ITEMS),
                },
                "items": FLAGGED_ITEMS,
            },
            indent=2,
        )
        + "\n"
    )

    # Generate human-readable line-by-line verification ledger markdown
    lines = [
        "# Complete Line-by-Line Primary-Source Verification Ledger (`C2`–`C6`)",
        "",
        f"- **Verification Date (UTC):** `{VERIFIED_DATE}`",
        f"- **Account Open Date Anchor:** `{OPEN_DATE}`",
        f"- **Auditor Session:** `session-6ce52089` (`arena/6ce52089-savings2`)",
        "- **Strict Zero-Hallucination Policy:** Every value is sourced exclusively from `.gov` agencies (`fdic.gov`, `api.fdic.gov`, `federalreserve.gov`, `home.treasury.gov`) or official bank domains (`synchrony.com`, `marcus.com`, `usbank.com`, `sofi.com`, `wellsfargo.com`, `capitalone.com`, `americanexpress.com`, `ally.com`, `bmo.com`, `chase.com`, `bankofamerica.com`, `citi.com`, `pnc.com`, `truist.com`, `td.com`, `citizensaccess.com`). Any unconfirmed/ZIP-gated cell is left strictly blank (`—`) and published on `flagged-review.html`.",
        "",
        "## Master Line-by-Line Account Verification Table",
        "",
        "| # | Institution (FDIC Cert #) | Account | Fed Rank | Verified APY | Official Rate Date | Min Open | Monthly Fee | Year-1 Return on $250k (`2026-10-22` → `2027-10-22`) | Primary Official Source |",
        "| :---: | :--- | :--- | :---: | :---: | :---: | :---: | :---: | :---: | :--- |",
    ]
    for idx, acct in enumerate(ACCOUNTS, start=1):
        r250 = calc_account_return(acct, 250000.0, 1.0)
        apy_str = f"**{acct['apy_percent']:.2f}%**" if acct["apy_percent"] is not None else "— *(Flagged)*"
